//! client.gen@1: a typed client for one cell, from its build descriptor. The module has one method
//! per op the cell described under T0; each call is signed with the guest key from the grant
//! string, so the client holds exactly the rights the grant gives and nothing more.
//!
//! Ops (POST /<Op>, JSON):
//!   Gen{descriptor, lang: "ts" | "py", instance, door} -> {file, module, usage}
//!
//! The grant string is `<guest secret seed hex>.<cap chain hex>`; the page shows it once.
//!
//!   client-gen serve [addr]
//!   client-gen gen <descriptor.json> <ts|py> <instance> <door>   prints the module

use std::sync::Arc;

use anyhow::{bail, Result};
use play_http::{json, Req, Resp, Value};

fn ident_ok(s: &str) -> bool {
    !s.is_empty() && s.len() <= 32 && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') && !s.starts_with(|c: char| c.is_ascii_digit())
}

pub fn gen(desc: &Value, lang: &str, instance: &str, door: &str) -> Result<Value> {
    let ops: Vec<String> = serde_json::from_value(desc["ops"].clone())?;
    if ops.is_empty() || !ops.iter().all(|o| ident_ok(o)) {
        bail!("descriptor ops must be identifiers");
    }
    if !instance.starts_with("c-") || !instance[2..].chars().all(|c| c.is_ascii_hexdigit()) {
        bail!("instance must look like c-<hex>");
    }
    if !(door.starts_with("https://") || door.starts_with("http://127.0.0.1") || door.starts_with("http://localhost")) || door.contains(['"', '\'', '\\', '\n', ' ']) {
        bail!("door must be an https URL (or http on localhost)");
    }
    let art = desc["artifact"]["sha256"].as_str().unwrap_or("");
    let (file, module, usage) = match lang {
        "ts" => {
            let methods: String = ops
                .iter()
                .map(|o| format!("  {o}(): Promise<number> {{ return this.call(\"{o}\"); }}\n"))
                .collect();
            let module = format!(
                r#"// Generated by client.gen@1 for cell {instance} (artifact {art}).
// Runs in browsers and Node 20+. Every call is signed with the guest key in the grant.
const DOOR = "{door}";
const INSTANCE = "{instance}";
const hex = (b: Uint8Array) => Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
const unhex = (s: string) => new Uint8Array(s.match(/../g)!.map((h) => parseInt(h, 16)));

export class Cell {{
  constructor(private key: CryptoKey, private chain: string) {{}}
  async call(op: string): Promise<number> {{
    const ts = Math.floor(Date.now() / 1000);
    const msg = new TextEncoder().encode(`play-call-v0\n${{INSTANCE}}\n${{op}}\n${{ts}}`);
    const sig = hex(new Uint8Array(await crypto.subtle.sign("Ed25519", this.key, msg)));
    const r = await fetch(`${{DOOR}}/api/call`, {{
      method: "POST",
      headers: {{ "content-type": "application/json" }},
      body: JSON.stringify({{ instance: INSTANCE, op, grant: {{ chain: this.chain, ts, sig }} }}),
    }});
    const v = await r.json();
    if (!r.ok) throw new Error(v.error);
    if (v.report.kind !== "ok") throw new Error(v.report.trap ?? v.report.error);
    return v.report.result;
  }}
{methods}}}

export async function connect(grant: string): Promise<Cell> {{
  const [seed, chain] = grant.split(".");
  // PKCS#8 wrapper for a raw 32-byte Ed25519 seed.
  const pkcs8 = new Uint8Array([...unhex("302e020100300506032b657004220420"), ...unhex(seed)]);
  const key = await crypto.subtle.importKey("pkcs8", pkcs8, "Ed25519", false, ["sign"]);
  return new Cell(key, chain);
}}
"#
            );
            let usage = format!("import {{ connect }} from \"./cell.ts\";\nconst cell = await connect(GRANT);\nconsole.log(await cell.{}());", ops[0]);
            ("cell.ts", module, usage)
        }
        "py" => {
            let methods: String = ops
                .iter()
                .map(|o| format!("    def {o}(self) -> int:\n        return self.call(\"{o}\")\n\n"))
                .collect();
            let module = format!(
                r#"# Generated by client.gen@1 for cell {instance} (artifact {art}).
# Needs Python 3.8+ and `cryptography`. Every call is signed with the guest key in the grant.
import json, time, urllib.error, urllib.request
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

DOOR = "{door}"
INSTANCE = "{instance}"


class Cell:
    def __init__(self, grant: str):
        seed, self.chain = grant.split(".")
        self.key = Ed25519PrivateKey.from_private_bytes(bytes.fromhex(seed))

    def call(self, op: str) -> int:
        ts = int(time.time())
        sig = self.key.sign(f"play-call-v0\n{{INSTANCE}}\n{{op}}\n{{ts}}".encode()).hex()
        body = json.dumps({{"instance": INSTANCE, "op": op, "grant": {{"chain": self.chain, "ts": ts, "sig": sig}}}})
        rq = urllib.request.Request(f"{{DOOR}}/api/call", body.encode(), {{"content-type": "application/json"}})
        try:
            v = json.load(urllib.request.urlopen(rq, timeout=30))
        except urllib.error.HTTPError as e:
            raise RuntimeError(json.load(e)["error"]) from None
        if v["report"]["kind"] != "ok":
            raise RuntimeError(v["report"].get("trap") or v["report"].get("error"))
        return v["report"]["result"]

{methods}
def connect(grant: str) -> Cell:
    return Cell(grant)
"#
            );
            let usage = format!("from cell import connect\ncell = connect(GRANT)\nprint(cell.{}())", ops[0]);
            ("cell.py", module, usage)
        }
        _ => bail!("lang must be ts or py"),
    };
    Ok(json!({ "file": file, "module": module, "usage": usage }))
}

fn handle(req: Req) -> Resp {
    let body = match req.json() {
        Ok(v) => v,
        Err(r) => return r,
    };
    match req.op() {
        "Gen" => match gen(&body["descriptor"], body["lang"].as_str().unwrap_or(""), body["instance"].as_str().unwrap_or(""), body["door"].as_str().unwrap_or("")) {
            Ok(v) => Resp::ok(v),
            Err(e) => Resp::error(400, &e.to_string()),
        },
        op => Resp::error(404, &format!("client.gen@1 has no op {op}")),
    }
}

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("serve") => {
            let addr = args.get(1).cloned().unwrap_or_else(|| "127.0.0.1:7864".into());
            play_http::serve(&addr, 2, Arc::new(handle))
        }
        Some("gen") if args.len() == 5 => {
            let desc: Value = serde_json::from_slice(&std::fs::read(&args[1])?)?;
            let v = gen(&desc, &args[2], &args[3], &args[4])?;
            print!("{}", v["module"].as_str().unwrap());
            Ok(())
        }
        _ => bail!("usage: client-gen serve [addr] | client-gen gen <descriptor.json> <ts|py> <instance> <door>"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn one_method_per_op_and_bad_ops_refused() {
        let d = json!({ "ops": ["incr", "get"], "artifact": { "sha256": "ab" } });
        let ts = gen(&d, "ts", "c-0a1b", "https://play.ce-net.com").unwrap();
        assert!(ts["module"].as_str().unwrap().contains("incr(): Promise<number>"));
        assert_eq!(ts["usage"].as_str().unwrap().lines().count(), 3);
        let py = gen(&d, "py", "c-0a1b", "https://play.ce-net.com").unwrap();
        assert!(py["module"].as_str().unwrap().contains("def get(self) -> int:"));
        let bad = json!({ "ops": ["x\"); evil(\""], "artifact": { "sha256": "ab" } });
        assert!(gen(&bad, "ts", "c-0a1b", "https://play.ce-net.com").is_err());
        assert!(gen(&d, "ts", "c-0a1b", "https://x\"").is_err());
    }
}
